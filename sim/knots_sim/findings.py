def write_breath_and_trees(d: dict) -> Path:
    """Findings 002: the breath's two routes over knot depth, and the tree of a parent and its children."""
    b, t, v = d["breath"], d["tree"], d["validation"]["squeeze"]
    run = d["run"]
    depths = b["depths"]
    pc = lambda x: f"{100 * x:.0f}%"
    cells = lambda xs: " | ".join("holds" if x is None else f"{x:.0f} s" for x in xs)
    route = {"even": "drive, even (±)", "uneven": "drive, uneven (−)", "settling": "drive, settling (−)",
             "movement": "movement (share of a squeeze)"}
    table = "\n".join(f"| {route[r['route']]} {r['size']:g} | {cells(r['release_s'])} |" for r in b["rows"])
    need = lambda k: " | ".join("none" if x is None else pc(x) for x in b["least_movement"][k])
    ease = b["easing"]
    fitted = next(r for r in ease["rows"] if r["fitted"])
    fast = next(r for r in ease["rows"] if abs(r["tau_down"] - 3.0) < 1e-9)
    tr, sib, fig = t["robustness"], t["siblings"], t["figure"]
    first = {e["vessel"]: e["t"] for e in fig["events"] if e["to"] == "shut"}
    opened = [e for e in fig["events"] if e["to"] == "open"]
    parent_open = next(e["t"] for e in opened if e["vessel"] == 0)
    with_it = [e for e in opened if e["vessel"] and e["t"] - parent_open < 5]
    last = max(opened, key=lambda e: e["t"])
    text = f"""# Breath and trees: two routes, and clusters. Findings 002

*Generated by `uv run python -m knots_sim.export` on {run['date']} (inputs {run['inputs']}). Every number comes from that
run. The model is `sim/knots_sim/models/vessel.py` (the movement route) and `sim/knots_sim/models/tree.py`; the trials
are `sim/knots_sim/breath.py`. The site shows the same results at /research/.*

## In brief

1. **The breath has two routes, and the model now carries both.** Through drive, as before. Through movement: a change of
   shape loosens the wall's force for a while, saturating, fitted to squeezed arteries (clifford2006): +{pc(v['one']['rise'])}
   after one 1 s squeeze (measured +{pc(v['one']['measured']['rise'])}), +{pc(v['long']['rise'])} after one of 5 s
   (+{pc(v['long']['measured']['rise'])}), +{pc(v['five']['rise'])} after five (+{pc(v['five']['measured']['rise'])}), peaking
   {v['five']['peak_s']:.1f}–{v['long']['peak_s']:.1f} s after release (measured {v['five']['measured']['peak_s']}–{v['long']['measured']['peak_s']} s).
   The wall answers changes of shape, not held shapes, so the loosening adds up over breaths.
2. **An even breath holds every knot; easy knots go first; the deepest hold.** Over {b['breaths']} slow breaths:

| route | {' | '.join(pc(x) for x in depths)} |
|---|{'---|' * len(depths)}
{table}

   (Columns: how far above its own reopening threshold the drive holding the knot sits, as a share of the band.)
3. **What would have to be true for movement to be the route**: the least deformation per breath, as a share of a squeeze
   that shuts the vessel:

| within | {' | '.join(pc(x) for x in depths)} |
|---|{'---|' * len(depths)}
| 3 breaths | {need('within_3')} |
| 10 breaths | {need('within_10')} |

4. **One breath or many turns on how fast the skin's small arteries ease when drive falls.** With the value fitted to the
   gasp's recovery ({fitted['tau_down']:.0f} s), an uneven breath (−{ease['swing']}) releases the easiest knot after
   {fitted['release_s'][0]:.0f} s; if they eased in 3 s, after {fast['release_s'][0]:.0f} s. Nobody has measured it over hairy skin.
5. **One knot upstream makes a cluster below it.** In the worked tree (a parent and four children with walls from 0.25 to
   0.35), a local surge shuts the parent at {first[0]:.0f} s and all four children within {max(first.values()) - first[0]:.1f} s,
   as the pressure below the parent collapses. Released after a 40 s press, the parent reopens at {parent_open:.0f} s and
   {len(with_it)} children with it within 5 s; the last lets go at {last['t']:.0f} s, after drive falls to rest.
6. **Across {tr['samples']} plausible trees** (pressures, the parent's resistance, the children's walls and the drive
   sampled): when the parent held a knot, a cluster formed beneath it in {pc(tr['share_cluster'])} ({tr['mean_cluster']:.1f}
   of 4 children on average); releasing the parent freed most of its cluster within 5 s in {pc(tr['share_cascade'])}; at
   least one child stayed held in {pc(tr['share_queue'])}.
7. **Siblings on one feed protect each other.** Each closure raises the pressure holding the others open: a surge of
   stress shut {sib['shut_by_surge']} of {sib['siblings']}. Clusters come from the tree's hierarchy.

## Limits

- The movement route is calibrated on rat muscle feed arteries squeezed shut, not on skin; how much a breath deforms the
  tissue at a knot is unmeasured, so it is swept.
- The tree's resistances and pressures are guesses, sampled across ranges; a real tree branches further.
- The author's observation that a parent's release frees its children (O13) was written down after these runs were
  shared: the match is found after the fact.
- These are what the mechanisms can do with measured numbers. They measure nothing.
"""
    OUT2.parent.mkdir(parents=True, exist_ok=True)
    OUT2.write_text(text)
    return OUT2
